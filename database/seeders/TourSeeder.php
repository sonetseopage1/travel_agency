    /**
     * Give each activity a time and an icon so the itinerary renders the same way
     * whether it was seeded here or saved through the admin tour form.
     *
     * @param  array<int, array<string, mixed>>  $itinerary
     * @return array<int, array<string, mixed>>
     */
    private function withTimedActivities(array $itinerary): array
    {
        return array_map(function (array $day, int $dayIndex): array {
            $dayNumber = $day['day'] ?? $dayIndex + 1;
            $startHour = $dayIndex === 0 ? 6 : 7;

            $activities = [];

            foreach ($day['activities'] ?? [] as $index => $activity) {
                $title = is_array($activity) ? ($activity['title'] ?? '') : (string) $activity;
                $hour = $startHour + intdiv($index, 2);
                $minute = $index % 2 === 0 ? '00' : '30';

                $activities[] = is_array($activity) ? $activity + [
                    'time' => sprintf('%02d:%s', min($hour, 22), $minute),
                    'icon' => $activity['icon'] ?? $this->iconFor($title),
                ] : [
                    'time' => sprintf('%02d:%s', min($hour, 22), $minute),
                    'icon' => $this->iconFor($title),
                    'title' => $title,
                    'location' => '',
                    'description' => '',
                ];
            }

            return [
                'day_title' => $day['day_title'] ?? sprintf('Day %02d — %s', $dayNumber, $day['title'] ?? 'ভ্রমণ'),
                'activities' => $activities,
            ];
        }, $itinerary, array_keys($itinerary));
    }

    /**
     * Pick an icon that matches the activity text.
     */
    private function iconFor(string $text): string
    {
        return match (true) {
